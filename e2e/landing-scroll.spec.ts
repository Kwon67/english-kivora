import { expect, test } from '@playwright/test'

test('a faixa leva ao exemplo escolhido e aceita o teclado', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: /B2 Independente/ }).click()
  const selected = page.getByRole('button', { name: 'B2', exact: true })
  await expect(selected).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#level-example')).toContainText('Here’s how I see it.')
  await selected.press('End')
  await expect(page.getByRole('button', { name: 'C2', exact: true })).toBeFocused()
  await expect(page.locator('#level-example')).toContainText('There’s more to it')
  await page.reload()
  await expect(page.getByRole('button', { name: 'C2', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('menu compacto fecha com Escape e navega para dúvidas', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const menu = page.getByRole('button', { name: 'Menu' })
  await menu.press('Enter')
  await expect(menu).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  await menu.click()
  await page.locator('#nav-links').getByRole('link', { name: 'Dúvidas' }).click()
  await expect(page).toHaveURL(/#faq$/)
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await page.locator('#faq summary').first().press('Enter')
  await expect(page.locator('#faq details[open] p')).toBeVisible()
})
