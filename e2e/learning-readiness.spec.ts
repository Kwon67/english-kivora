test('dictionary recovers from failure and distinguishes an empty result',async({page})=>{
 let calls=0
 await page.route('**/api/dictionary?**',r=>{
  calls++
  const successful = {word:'take a break',lookup:'take a break',entries:[],dictionaryAvailable:true,translation:'fazer uma pausa'}
  const response = [ {error:'Pesquisa indisponível no teste.'}, { ...successful, entries:null }, successful ][calls-1]
  return r.fulfill({status:calls===1?503:200,json:response})
 })
 await page.goto('/dictionary')
 await page.getByLabel('Palavra ou expressão em inglês').fill('take a break')
 await page.getByRole('button',{name:'Pesquisar',exact:true}).click()
 await expect(page.getByRole('alert').filter({hasText:'Pesquisa indisponível no teste.'})).toBeVisible()
 await page.getByRole('button',{name:'Pesquisar',exact:true}).click()
 await expect(page.getByRole('alert').filter({hasText:'Não foi possível ler o resultado'})).toBeVisible()
 await expect(page.getByLabel('Palavra ou expressão em inglês')).toHaveValue('take a break')
 await page.getByRole('button',{name:'Pesquisar',exact:true}).click()
 await expect(page.getByRole('region',{name:'take a break',exact:true})).toContainText('fazer uma pausa')
 await expect(page.getByText('Não encontramos um verbete para esta pesquisa.',{exact:false})).toBeVisible()
 await expect(page.getByRole('button',{name:'break',exact:true})).toBeVisible()

 await page.clock.install()
 let releaseRequest = () => {}
 const stalled = new Promise<void>(resolve => { releaseRequest = resolve })
 await page.route('**/api/dictionary?**', async r => {
  await stalled
  await r.abort().catch(() => undefined)
 }, { times:1 })
 try {
  const inFlight = page.waitForRequest('**/api/dictionary?**')
  await page.getByRole('button',{name:'break',exact:true}).click()
  await inFlight
  await page.clock.fastForward(15_001)
  await expect(page.getByRole('alert').filter({hasText:'demorou mais que o esperado'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Pesquisar',exact:true})).toBeEnabled()
 } finally { releaseRequest() }
})

