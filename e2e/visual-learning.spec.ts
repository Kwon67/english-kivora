import { expect, test } from '@playwright/test'

test('grammar separates selection from correctness and teaches after a mistake', async ({ page }) => {
  await page.goto('/')
  const practice = page.locator('#como-funciona')
  await expect(practice.getByRole('button', { name: 'Confirmar', exact: true })).toBeDisabled()
  await practice.getByRole('button', { name: 'an', exact: true }).click()
  await expect(practice.getByRole('button', { name: 'an', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await practice.getByRole('button', { name: 'Confirmar', exact: true }).click()
  await expect(practice.getByRole('status')).toContainText('Para dizer “um livro”, use “a book”')
  await practice.getByRole('button', { name: 'Tentar de novo' }).click()
  await expect(practice.getByRole('button', { name: 'a', exact: true })).toBeFocused()
  for (const answer of ['a', 'an', 'two']) {
    await practice.getByRole('button', { name: answer, exact: true }).click()
    await practice.getByRole('button', { name: 'Confirmar', exact: true }).click()
    await expect(practice.getByRole('status')).toContainText('Muito bem!')
    await practice.getByRole('button', { name: answer === 'two' ? 'Praticar novamente' : 'Continuar', exact: true }).click()
  }
  await expect(practice.getByText('1 / 3', { exact: true })).toBeVisible()
})

test('sentence building gives a repair path and spaced recall uses different intervals', async ({ page }) => {
  await page.goto('/')
  const practice = page.locator('#como-funciona')
  await practice.getByRole('button', { name: 'Montar', exact: true }).click()
  for (const word of ['please?', 'a coffee,', 'Can I have']) await practice.getByRole('button', { name: word, exact: true }).click()
  await practice.getByRole('button', { name: 'Verificar frase' }).click()
  await expect(practice.getByText(/Comece com “Can I have”/)).toBeVisible()
  await practice.getByRole('button', { name: 'Recomeçar frase' }).click()
  for (const word of ['Can I have', 'a coffee,', 'please?']) await practice.getByRole('button', { name: word, exact: true }).click()
  await practice.getByRole('button', { name: 'Verificar frase' }).click()
  await expect(practice.getByText(/Você já pode usar essa frase/)).toBeVisible()
  await practice.getByRole('button', { name: 'Relembrar', exact: true }).click()
  await practice.getByRole('button', { name: 'Revelar significado' }).click()
  await expect(practice.getByText('um pouco mais perto', { exact: true })).toBeVisible()
  await practice.getByRole('button', { name: /^De novo/ }).click()
  const first = await practice.getByText(/Neste exemplo, a palavra voltaria/).innerText()
  await practice.getByRole('button', { name: /^Fácil/ }).click()
  expect(await practice.getByText(/Neste exemplo, a palavra voltaria/).innerText()).not.toBe(first)
})

