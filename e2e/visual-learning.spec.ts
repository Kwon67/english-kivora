for (const [width, height] of [[320, 568], [390, 844], [768, 1024], [1024, 768], [1440, 1000], [2560, 1440], [844, 390]]) {
  test(`public layout and game controls at ${width}x${height}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/')
    await expect(page.getByRole('heading', { name: 'Seu inglês ganha vida.' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await page.screenshot({ path: testInfo.outputPath(`home-${width}.png`), fullPage: true })
    const practice = page.locator('#como-funciona')
    await practice.getByRole('button', { name: 'a', exact: true }).click()
    await practice.getByRole('button', { name: 'Confirmar', exact: true }).click()
    await expect(practice.getByRole('status')).toContainText('Muito bem!')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await practice.screenshot({ path: testInfo.outputPath(`practice-${width}.png`) })
    expect(errors).toEqual([])
  })
}

test('reduced motion, mobile menu focus and no-JS content', async ({ page, browser, baseURL }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const menu = page.getByRole('button', { name: 'Abrir menu', exact: true })
  await menu.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  await expect(page.locator('[data-scroll-art]')).not.toHaveAttribute('style', /transform/)
  const context = await browser.newContext({ javaScriptEnabled: false })
  const staticPage = await context.newPage()
  await staticPage.goto(baseURL!)
  await expect(staticPage.getByRole('heading', { name: 'Seu inglês ganha vida.' })).toBeVisible()
  await expect(staticPage.locator('#produto').getByRole('link', { name: 'Começar grátis' })).toHaveAttribute('href', '/register')
  await context.close()
})

const fixtureURL = process.env.KIVORA_FIXTURE_URL
test.describe('isolated learning fixtures', () => {
  test.skip(!fixtureURL, 'Set KIVORA_FIXTURE_URL to the isolated fixture app; never a production app.')

  test('real multiple choice confirms exactly once with mouse and keyboard', async ({ page }) => {
    await page.goto(`${fixtureURL}/practice`)
    await page.getByRole('button', { name: 'Opção: Olá', exact: true }).click()
    await page.getByRole('button', { name: 'Confirmar', exact: true }).evaluate((button: HTMLButtonElement) => { button.click(); button.click() })
    await expect(page.getByTestId('result')).toHaveText('correct')
    await expect(page.getByTestId('answer-count')).toHaveText('1')
    await expect(page.getByRole('button', { name: 'Opção: Olá', exact: true })).toHaveAttribute('data-result', 'correct')
    await page.reload()
    await page.getByRole('button', { name: 'Opção: Bom dia', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(page.getByTestId('answer-count')).toHaveText('0')
    await page.getByRole('button', { name: 'Confirmar', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(page.getByTestId('result')).toHaveText('wrong')
    await expect(page.getByTestId('answer-count')).toHaveText('1')
  })

  test('review retains a failed answer, retries once and clears the mobile dock', async ({ page, request }) => {
    await request.post(`${fixtureURL}/api/product-fixture`, { data: { fail: 1 } })
    await page.setViewportSize({ width: 320, height: 568 })
    await page.goto(`${fixtureURL}/home`)
    const original = await page.locator('.memory-card h2').innerText()
    const reveal = page.getByRole('button', { name: 'Mostrar resposta' })
    await reveal.scrollIntoViewIfNeeded()
    const revealBox = await reveal.boundingBox()
    const dock = await page.getByRole('navigation', { name: 'Navegação rápida' }).boundingBox()
    expect(revealBox!.y + revealBox!.height).toBeLessThanOrEqual(dock!.y)
    await reveal.click()
    const memory = await page.locator('.memory-card').boundingBox()
    const grades = await page.locator('.study-grades').boundingBox()
    expect(grades!.y).toBeGreaterThanOrEqual(memory!.y + memory!.height)
    await page.getByRole('button', { name: /^Lembrei/ }).click()
    await expect(page.locator('.product-error')).toBeVisible()
    await expect(page.locator('.memory-card h2')).toHaveText(original)
    await page.getByRole('button', { name: /^Lembrei/ }).evaluate((button: HTMLButtonElement) => { button.click(); button.click() })
    await expect(page.locator('.memory-card h2')).not.toHaveText(original)
    await page.reload()
    await expect(page.locator('.memory-card h2')).not.toHaveText(original)
    const state = await (await request.get(`${fixtureURL}/api/product-fixture`)).json()
    expect(state.reviews).toHaveLength(1)
  })
})
